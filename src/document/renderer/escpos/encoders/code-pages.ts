function buildCodePointToByteMap(extendedByCodePoint: ReadonlyMap<number, number>): ReadonlyMap<number, number> {
  const map = new Map<number, number>();
  for (let byte = 0x00; byte < 0x80; byte += 1) {
    map.set(byte, byte);
  }
  for (const [byte, codePoint] of extendedByCodePoint) {
    map.set(codePoint, byte);
  }
  return map;
}

function cp437Map(): ReadonlyMap<number, number> {
  const extended = new Map<number, number>();
  CP437_EXTENDED.forEach((codePoint, index) => extended.set(0x80 + index, codePoint));
  return buildCodePointToByteMap(extended);
}

function wpc1252Map(): ReadonlyMap<number, number> {
  const extended = new Map<number, number>(WPC1252_LOW_EXTENDED);
  for (let byte = 0xa0; byte <= 0xff; byte += 1) {
    extended.set(byte, byte); // identity range
  }
  return buildCodePointToByteMap(extended);
}

const CODE_POINT_TO_BYTE: Record<Exclude<CodePage, CodePage.Utf8>, ReadonlyMap<number, number>> = {
  [CodePage.Cp437]: cp437Map(),
  [CodePage.Wpc1252]: wpc1252Map(),
};

/** Maps a single Unicode code point to its byte in the given code page, or `undefined` if unmapped. */
export function mapCodePointToByte(codePage: Exclude<CodePage, CodePage.Utf8>, codePoint: number): number | undefined {
  return CODE_POINT_TO_BYTE[codePage].get(codePoint);
}
