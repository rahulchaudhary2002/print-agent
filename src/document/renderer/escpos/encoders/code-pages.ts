export enum CodePage {
  /** No translation — writes the raw UTF-8 bytes and relies on the printer's own UTF-8 mode. */
  Utf8 = 'utf-8',
  Cp437 = 'cp437',
  Wpc1252 = 'wpc1252',
}

/** ESC/POS `ESC t n` character-table index per code page (Epson TM-family numbering). */
export const CODE_PAGE_TABLE_INDEX: Record<Exclude<CodePage, CodePage.Utf8>, number> = {
  [CodePage.Cp437]: 0,
  [CodePage.Wpc1252]: 16,
};

